import { createHash } from 'node:crypto';
import { readFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { build } from 'esbuild';

// Bundles the extension's scripts (two content scripts, the service worker and the results page's script), including the
// card reader (src/card-reader), into classic scripts that Chrome loads unpacked. Unminified so the loaded code stays
// reviewable.
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
// The results page shows the manifest version in its header, so a reload can be confirmed there.
const { version } = JSON.parse(readFileSync(path.join(root, 'manifest.json'), 'utf8'));

// content.js: the app page analysis (isolated world). model-export.js: the model export, which runs in the classic model
// building page's main world to read its Model settings grids through the page's own client. It holds the builder of the
// model map's graph (src/map/build-graph.ts) too: the export makes its Dynamic Cell Access file from that graph's access
// links. background.js: the service worker behind the toolbar icon. results.js: the results page's script, which
// results.html loads as a classic script. It holds the model map (src/map) as well, through the page's imports: the map
// has no bundle of its own.
const BUNDLES = [['content.ts', 'content.js'], ['model-content.ts', 'model-export.js'], ['background.ts', 'background.js'], ['results/main.ts', 'results.js']];
const READER = 'model-content.ts';
const options = (entry, outfile, define) => ({
  absWorkingDir: root,
  entryPoints: [path.join(root, 'src', entry)],
  outfile: path.join(root, 'dist', outfile),
  bundle: true,
  format: 'iife',
  platform: 'browser',
  target: ['chrome111'],
  charset: 'utf8',
  legalComments: 'none',
  logLevel: 'warning',
  define,
});

// The mark of the model's reader, model-export.js, in every bundle of the build. The reader says it when it checks in, and
// the content script reads a model only with a reader of its own build (src/bridge.ts): a tab keeps the reader it loaded
// with until it is refreshed, through a reload of the extension too. Made from the version and the sources the reader is
// bundled from, each with its lines ended alike, so that the same files give the same bundles on every run and on every
// system, and a build that leaves the reader as it was leaves a model's tab as good as refreshed.
const { metafile } = await build({ ...options(READER, 'model-export.js', { __EXTENSION_VERSION__: JSON.stringify(version) }), write: false, metafile: true });
const marked = createHash('sha256').update(version);
for (const input of Object.keys(metafile.inputs).sort()) marked.update(`\0${input}\0`).update(readFileSync(path.join(root, input), 'utf8').replace(/\r\n/g, '\n'));
const readerMark = marked.digest('hex').slice(0, 12);

for (const [entry, outfile] of BUNDLES) {
  await build({
    ...options(entry, outfile, { __EXTENSION_VERSION__: JSON.stringify(version), __EXTENSION_BUILD__: JSON.stringify(readerMark) }),
    banner: { js: `// Cardigan ${version}, model reader ${readerMark}. Generated by scripts/build.mjs from src; do not edit.` },
  });
  console.log(`Built dist/${outfile}`);
}
console.log(`Cardigan ${version}, model reader ${readerMark}`);
